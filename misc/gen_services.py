'''
Generate a service list for the net_port completer.

Reads an /etc/services file and prints a Python list of
`(name, port, alias, description)` tuples.

Identical tuples are listed only once.

Usage:  python3 misc/gen_services.py [FILE]

FILE defaults to /etc/services.
'''

import re
import sys


DEFAULT_FILE = '/etc/services'

PROTOCOL_RE = re.compile(r'[A-Za-z0-9-]+')


def parse(text):
    rows = []
    seen = set()

    for line in text.splitlines():
        line = line.strip()

        if not line or line.startswith('#'):
            continue

        fields, _, comment = line.partition('#')
        comment = comment.strip()
        parts = fields.split()

        if len(parts) < 2:
            raise ValueError('Malformed line: %s' % line)

        name, port_proto = parts[0], parts[1]
        alias = ' '.join(parts[2:])

        port, _, protocol = port_proto.partition('/')

        if not port.isdigit() or not PROTOCOL_RE.fullmatch(protocol):
            raise ValueError('Malformed port: %s' % line)

        row = (name, port, alias, comment)

        if row not in seen:
            seen.add(row)
            rows.append(row)

    return rows


def render(rows):
    lines = [
        '# Generated by misc/gen_services.py from /etc/services.',
        '_SERVICES = [',
    ]

    for name, port, alias, description in rows:
        row = '({})'.format(', '.join(repr(part) for part in (
            name, port, alias, description)))
        lines.append('    %s,' % row)

    lines.append(']')

    return '\n'.join(lines) + '\n'


def main():
    file = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FILE

    with open(file, encoding='utf-8') as handle:
        print(render(parse(handle.read())), end='')


if __name__ == '__main__':
    main()
