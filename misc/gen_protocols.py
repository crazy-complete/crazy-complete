'''
Generate a protocol list for the ip_protocol completer.

Reads an /etc/protocols file and prints a Python list of
`(name, number, alias, description)` tuples.

Usage:  python3 misc/gen_protocols.py [FILE]

FILE defaults to /etc/protocols.
'''

import sys


DEFAULT_FILE = '/etc/protocols'


def parse(text):
    rows = []

    for line in text.splitlines():
        line = line.strip()

        if not line or line.startswith('#'):
            continue

        fields, _, comment = line.partition('#')
        comment = comment.strip()
        parts = fields.split()

        if len(parts) < 2:
            raise ValueError('Malformed line: %s' % line)

        name, number = parts[0], parts[1]
        alias = ' '.join(parts[2:])

        rows.append((name, number, alias, comment))

    return rows


def render(rows):
    lines = [
        '# Generated by misc/gen_protocols.py from /etc/protocols.',
        '_AVAILABLE_PROTOCOLS = [',
    ]

    for name, number, alias, description in rows:
        row = '({})'.format(', '.join(repr(part) for part in (
            name, number, alias, description)))
        lines.append('    %s,' % row)

    lines.append(']')

    return '\n'.join(lines) + '\n'


def main():
    file = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FILE

    with open(file, encoding='utf-8') as handle:
        print(render(parse(handle.read())), end='')


if __name__ == '__main__':
    main()
