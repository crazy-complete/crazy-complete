_FIELDS = ('name', 'port', 'alias', 'description')

_error = CrazySchemaValidationError


def _expand(template, row):
    text = Template(template).substitute(**dict(zip(_FIELDS, row)))
    return text.replace('`', "'")


def _placeholders(template):
    template_obj = Template(template)
    return [match.group('named') or match.group('braced')
            for match in template_obj.pattern.finditer(template_obj.template)
            if match.group('escaped') is None]


def _check_placeholders(template, parameter, spec):
    placeholders = _placeholders(template)

    if None in placeholders:
        raise _error('%s: %s' % (parameter, m.invalid_value()), spec)

    for placeholder in placeholders:
        if placeholder not in _FIELDS:
            values = ', '.join('`${%s}`' % field for field in _FIELDS)
            message = '%s: %s' % (parameter, m.invalid_value_expected_values(values))
            raise _error(message, spec)


def _pairs(value_template, description_template):
    uses_description = 'description' in _placeholders(description_template)
    merged = {}

    for name, port, alias, description in _SERVICES:
        row = (name, port, alias, description)
        value = _expand(value_template, row)

        if not value:
            continue

        # Drop rows that carry no description: a template such as
        # '${port} - ${description}' would otherwise leave a dangling
        # fragment like '750 -' in the joined description.
        if description or not uses_description:
            description = _expand(description_template, row)
        else:
            description = None

        entries = merged.setdefault(value, [])

        if description:
            entries.append(description)

    return [(value, ', '.join(dict.fromkeys(entries)) if entries else None)
            for value, entries in merged.items()]


def validate(_ctxt, arguments):
    '''Validate YAML for the net_port completer'''
    value = arguments.get_required_arg('value')
    description = arguments.get_required_arg('description')
    arguments.require_no_more()

    check_type(value, (str,), 'value')
    check_type(description, (str,), 'description')
    check_non_empty_string(value, 'value')
    check_non_empty_string(description, 'description')

    _check_placeholders(value.value, 'value', value)
    _check_placeholders(description.value, 'description', description)


def bash(completer, ctxt, trace, value, description):
    '''Implement net_port for bash'''
    pairs = _pairs(value, description)
    return completer.complete_from_def(ctxt, trace, ['choices', dict(pairs)])


