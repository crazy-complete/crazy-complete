_error = CrazySchemaValidationError


def validate(ctxt, arguments):
    '''Validate YAML for key_value_list completer'''
    pair_separator = arguments.get_required_arg('pair_separator')
    value_separator = arguments.get_required_arg('value_separator')
    values = arguments.get_required_arg('values')
    condition_func = arguments.get_optional_arg(None)
    arguments.require_no_more()

    check_type(pair_separator, (str,), 'pair_separator')
    check_type(value_separator, (str,), 'value_separator')
    check_type(values, (list,), 'values')
    check_type(condition_func, (str, NoneType), 'condition_func')

    ctxt.trace.append('key_value_list')

    check_char(pair_separator, 'pair_separator')
    check_char(value_separator, 'value_separator')
    check_non_empty_list(values, 'values')
    if condition_func.value is not None:
        check_non_empty_string(condition_func, 'condition_func')

    defined_keys = set()

    for i, compldef in enumerate(values.value):
        index = f'definition[{i}]'
        check_type(compldef, (list,), index)

        if len(compldef.value) < 3:
            msg = '%s: %s' % (index, m.list_must_contain_at_least_n_items('3'))
            raise _error(msg, compldef)

        if len(compldef.value) > 4:
            msg = '%s: %s' % (index, m.list_must_contain_exact_n_items('3/4'))
            raise _error(msg, compldef)

        key = compldef.value[0]
        description = compldef.value[1]
        complete = compldef.value[2]

        check_type(key, (str,), f'{index}: key')
        check_type(description, (str, NoneType), f'{index}: description')
        check_type(complete, (list, NoneType), f'{index}: completer')
        check_non_empty_string(key, f'{index}: key')
        check_no_spaces(key, f'{index}: key')

        if key.value in defined_keys:
            cause = f'{index}: {key.value}'
            msg = '%s: Duplicate key' % cause
            raise _error(msg, key)

        defined_keys.add(key.value)

        if complete.value is not None:
            check_complete(ctxt, complete)

        if len(compldef.value) == 4:
            excludes = compldef.value[3]
            check_type(excludes, (list,), f'{index}: excludes')
            for i2, exclude in enumerate(excludes.value):
                check_type(exclude, (str,), f'{index}: excludes[{i2}]')
                check_non_empty_string(exclude, f'{index}: excludes[{i2}]')

    # Check if keys which are specified in `excludes` actually exist
    for i, compldef in enumerate(values.value):
        if len(compldef.value) != 4:
            continue

        index = f'definition[{i}]'
        for i2, exclude in enumerate(compldef.value[3].value):
            if exclude.value not in defined_keys:
                cause = f'definition[{i}]: excludes[{i2}]: {exclude.value}'
                msg = '%s: No such key' % cause
                raise _error(msg, exclude)


class BashCompleteKeyValueList(BashCompletionCode):
    '''Used for completing a list of key-value pairs.'''

    # pylint: disable=too-many-arguments
    # pylint: disable=too-many-positional-arguments

    def __init__(self, ctxt, trace, completer, pair_separator, value_separator,
                 values, condition_func):
        args = []

        for definition in utils.get_key_value_list_definitions(values):
            if not definition.completer:
                func = 'false'
            elif definition.completer[0] == 'none':
                func = 'true'
            else:
                obj = completer.complete_from_def(ctxt, trace, definition.completer)
                func = obj.get_function()

            excludes = []
            if not definition.repeatable:
                excludes.append(definition.key)
            excludes.extend(definition.excludes)

            condition = ''
            if condition_func is not None:
                condition = '$c %s && ' % shell.quote(definition.key)

            args.append('%sa+=(%s %s %s)' % (
                condition,
                shell.quote(definition.key),
                shell.quote(func),
                shell.quote(' '.join(excludes))))

        code = 'local -a a=()\n'
        if condition_func is not None:
            code += 'local c=%s\n' % shell.quote(condition_func)
        code += '%s\n' % '\n'.join(args)
        code += '%s %s %s "${a[@]}"' % (
            ctxt.helpers.use_function('key_value_list'),
            shell.quote(pair_separator),
            shell.quote(value_separator)
        )

        super().__init__(ctxt, code)


class FishCompleteKeyValueList(FishCompletionCommand):
    '''Used for completing a list of key-value pairs.'''

    # pylint: disable=too-many-arguments
    # pylint: disable=too-many-positional-arguments

    def __init__(self, ctxt, trace, completer, pair_separator, value_separator,
                 values, condition_func):
        trace.append('key_value_list')

        args = []

        for definition in utils.get_key_value_list_definitions(values):
            if not definition.completer:
                func = 'false'
            elif definition.completer[0] == 'none':
                func = 'true'
            else:
                obj = completer.complete_from_def(ctxt, trace, definition.completer)
                func = obj.get_function()

            excludes = []
            if not definition.repeatable:
                excludes.append(definition.key)
            excludes.extend(definition.excludes)

            condition = ''
            if condition_func is not None:
                condition = '$c %s && ' % (shell.quote(definition.key))

            args.append('%sset -a a %s %s %s %s' % (
                condition,
                shell.quote(definition.key),
                shell.quote(definition.description or ''),
                shell.quote(func),
                shell.quote(' '.join(excludes))))

        code = 'set -l a\n'
        if condition_func is not None:
            code += 'set -l c %s\n' % shell.quote(condition_func)
        code += '%s\n' % '\n'.join(args)
        code += '%s %s %s $a' % (
            ctxt.helpers.use_function('key_value_list'),
            shell.quote(pair_separator),
            shell.quote(value_separator),
        )

        func = ctxt.helpers.add_dynamic_func(ctxt, code)

        super().__init__(ctxt, [func])


class ZshKeyValueList(ZshComplFunc):
    '''Used for completing a comma-separated list of key-value pairs.'''

    # pylint: disable=too-many-arguments
    # pylint: disable=too-many-positional-arguments

    def __init__(self, ctxt, trace, completer, pair_separator, value_separator,
                 values, condition_func):
        trace.append('key_value_list')
        spec = []

        for definition in utils.get_key_value_list_definitions(values):
            desc = ''
            if definition.description:
                desc = shell.quote('[%s]' % escape_square_brackets(definition.description))

            excludes = ''
            if definition.excludes:
                excludes = shell.quote('(%s)' % ' '.join(definition.excludes))

            repeatable = ''
            if definition.repeatable:
                repeatable = "'*'"

            condition = ''
            if condition_func is not None:
                condition = '$c %s && ' % (definition.key)

            key = escape_colon(definition.key)
            if not definition.completer:
                spec.append(f'{condition}a+=({excludes}{repeatable}{key}{desc})')
            elif definition.completer[0] == 'none':
                spec.append(f'{condition}a+=({excludes}{repeatable}{key}{desc}:::)')
            else:
                compl_obj = completer.complete_from_def(ctxt, trace, definition.completer)
                action = compl_obj.get_action_string()
                spec.append(f'{condition}a+=({excludes}{repeatable}{key}{desc}:::{action})')

        code = 'local -a a=()\n'
        if condition_func is not None:
            code += 'local c=%s\n' % shell.quote(condition_func)
        code += '%s\n' % '\n'.join(spec)
        code += '_values -s %s -S %s %s "${a[@]}"' % (
            shell.quote(pair_separator),
            shell.quote(value_separator),
            shell.quote(ctxt.option.metavar or ''),
        )

        func = ctxt.helpers.add_dynamic_func(ctxt, code)

        super().__init__(ctxt, [func], needs_braces=True)


