_error = CrazySchemaValidationError


def validate(ctxt, arguments):
    '''Validate YAML for key_value_pair completer'''
    value_separator = arguments.get_required_arg('value_separator')
    values = arguments.get_required_arg('values')
    condition_func = arguments.get_optional_arg(None)
    arguments.require_no_more()

    check_type(value_separator, (str,), 'value_separator')
    check_type(values, (list,), 'values')
    check_type(condition_func, (str, NoneType), 'condition_func')

    ctxt.trace.append('key_value_pair')

    check_char(value_separator, 'value_separator')
    check_non_empty_list(values, 'values')
    if condition_func.value is not None:
        check_non_empty_string(condition_func, 'condition_func')

    for i, compldef in enumerate(values.value):
        index = f'definition[{i}]'
        check_type(compldef, (list,), index)

        if len(compldef.value) != 3:
            msg = '%s: %s' % (index, m.list_must_contain_exact_n_items('3'))
            raise _error(msg, compldef)

        key = compldef.value[0]
        description = compldef.value[1]
        complete = compldef.value[2]

        check_type(key, (str,), f'{index}: key')
        check_type(description, (str, NoneType), f'{index}: description')
        check_type(complete, (list, NoneType), f'{index}: completer')
        check_non_empty_string(key, f'{index}: key')
        check_no_spaces(key, f'{index}: key')

        if complete.value is None:
            continue

        check_complete(ctxt, complete)


class BashCompleteKeyValuePair(BashCompletionCode):
    '''Used for completing a single of key-value pair.'''

    # pylint: disable=too-many-arguments
    # pylint: disable=too-many-positional-arguments

    def __init__(self, ctxt, trace, completer, value_separator, values,
                 condition_func):
        args = []

        for key, _desc, complete in values:
            if not complete:
                func = 'false'
            elif complete[0] == 'none':
                func = 'true'
            else:
                obj = completer.complete_from_def(ctxt, trace, complete)
                func = obj.get_function()

            condition = ''
            if condition_func is not None:
                condition = '$c %s && ' % shell.quote(key)

            args.append('%sa+=(%s %s)' % (
                condition,
                shell.quote(key),
                shell.quote(func)))

        code = 'local -a a=()\n'
        if condition_func is not None:
            code += 'local c=%s\n' % shell.quote(condition_func)
        code += '%s\n' % '\n'.join(args)
        code += '%s %s "${a[@]}"' % (
            ctxt.helpers.use_function('key_value_pair'),
            shell.quote(value_separator),
        )

        super().__init__(ctxt, code)


class FishCompleteKeyValuePair(FishCompletionCommand):
    '''Used for completing a single key-value pair.'''

    # pylint: disable=too-many-arguments
    # pylint: disable=too-many-positional-arguments

    def __init__(self, ctxt, trace, completer, value_separator, values,
                 condition_func):
        trace.append('key_value_pair')

        args = []

        for key, desc, complete in values:
            if not complete:
                func = 'false'
            elif complete[0] == 'none':
                func = 'true'
            else:
                obj = completer.complete_from_def(ctxt, trace, complete)
                func = obj.get_function()

            condition = ''
            if condition_func is not None:
                condition = '$c %s && ' % shell.quote(condition_func)

            args.append('%sset -a a %s %s %s' % (
                condition,
                shell.quote(key),
                shell.quote(desc or ''),
                shell.quote(func)))

        code = 'set -l a\n'
        if condition_func is not None:
            code += 'set -l c %s\n' % shell.quote(condition_func)
        code += '%s\n' % '\n'.join(args)
        code += '%s %s $a' % (
            ctxt.helpers.use_function('key_value_pair'),
            shell.quote(value_separator),
        )

        func = ctxt.helpers.add_dynamic_func(ctxt, code)

        super().__init__(ctxt, [func])


class ZshKeyValuePair(ZshComplFunc):
    '''Used for completing a single key-value pair.'''

    # pylint: disable=too-many-arguments
    # pylint: disable=too-many-positional-arguments

    def __init__(self, ctxt, trace, completer, value_separator, values,
                 condition_func):
        trace.append('key_value_pair')
        spec = []

        for key, desc, complete in values:
            if desc:
                desc = shell.quote('[%s]' % escape_square_brackets(desc))
            else:
                desc = ''

            condition = ''
            if condition_func is not None:
                condition = '$c %s && ' % shell.quote(key)

            key = escape_colon(key)
            if not complete:
                spec.append(f'{condition}a+=({key}{desc})')
            elif complete[0] == 'none':
                spec.append(f'{condition}a+=({key}{desc}:::)')
            else:
                compl_obj = completer.complete_from_def(ctxt, trace, complete)
                action = compl_obj.get_action_string()
                spec.append(f'{condition}a+=({key}{desc}:::{action})')

        code = 'local -a a=()\n'
        if condition_func is not None:
            code += 'local c=%s\n' % shell.quote(condition_func)
        code += '%s\n' % '\n'.join(spec)
        code += '_values -S %s %s "${a[@]}"' % (
            shell.quote(value_separator),
            shell.quote(ctxt.option.metavar or '')
        )

        func = ctxt.helpers.add_dynamic_func(ctxt, code)

        super().__init__(ctxt, [func], needs_braces=True)


def bash(completer, ctxt, trace, value_separator, values, condition_func=None):
    '''Implement key_value_pair for bash'''
    return BashCompleteKeyValuePair(
        ctxt, trace, completer, value_separator, values, condition_func)


