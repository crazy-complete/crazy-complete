'''ANSI escape sequences for colored terminal output.'''

# Colors
BLACK   = '\033[30m'
RED     = '\033[31m'
GREEN   = '\033[32m'
YELLOW  = '\033[33m'
BLUE    = '\033[34m'
MAGENTA = '\033[35m'
CYAN    = '\033[36m'
WHITE   = '\033[37m'

# Bold colors
BOLD_BLACK   = '\033[90m'
BOLD_RED     = '\033[91m'
BOLD_GREEN   = '\033[92m'
BOLD_YELLOW  = '\033[93m'
BOLD_BLUE    = '\033[94m'
BOLD_MAGENTA = '\033[95m'
BOLD_CYAN    = '\033[96m'
BOLD_WHITE   = '\033[97m'

# Style
BOLD      = '\033[1m'
UNDERLINE = '\033[4m'
RESET     = '\033[0m'
